/* Uma chave estrangeira é uma coluna ou grupo de colunas em uma tabela que identifica
unicamente  uma linha em outra tabela.

* Ou seja, i,a chave estrangeira é definida em uma tabela onde ele é apenas uma referência
e não contém todos os dados.

* Então uma chave estrangeira é simplesmente uma coluna ou grupo de colunas que  
é uma chave primária em outra tabela.

* A tabela que contém a chave estrangeira é chamada e tabela referênciadora ou tabela filho.
E a tabela na qual a chave estrangeira é referênciada é chamada de tabela pai.

* Uma tabela pode ter mais de uma chave estrangeira dependendo do seu relacionamento com 
outras tabelas. */

